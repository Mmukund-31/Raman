"""Generate SYNTHETIC reference/example spectra (Lorentzian bands at approximate literature positions).
These are NOT measurements. Run: py data/generate_synthetic.py"""
import json, pathlib
import numpy as np

OUT = pathlib.Path(__file__).parent
X = np.arange(600, 3001, 2.0)
BANDS = {  # name: [(center cm-1, relative height, hwhm)]
    "polypropylene": [(808,.5,6),(841,.45,6),(974,.35,6),(998,.4,6),(1151,.3,7),(1220,.35,7),(1330,.3,8),(1435,.4,8),(1458,.5,8),(2840,.9,12),(2870,.8,10),(2920,1.0,12),(2950,.7,10)],
    "ethanol": [(883,1.0,7),(1052,.35,8),(1095,.3,8),(1275,.25,9),(1455,.45,10),(2876,.8,10),(2928,.7,10),(2974,.75,10)],
    "paracetamol": [(797,.4,6),(857,.5,6),(968,.3,6),(1168,.45,7),(1236,.6,8),(1323,.9,8),(1371,.5,8),(1561,.4,8),(1648,.8,9),(2931,.35,12),(3064,.4,12)],
    "isopropanol": [(819,1.0,7),(953,.3,8),(1130,.25,9),(1450,.45,10),(2880,.7,10),(2938,.8,10),(2973,.85,10)],
    "beta_carotene": [(1008,.35,6),(1156,.9,7),(1520,1.0,7)],
}
def spec(bands):
    y = np.zeros_like(X)
    for c, h, w in bands: y += h / (1 + ((X - c) / w) ** 2)
    return y
refs = {}
for n, b in BANDS.items():
    y = spec(b); refs[n] = y
    np.savetxt(OUT / "references" / f"{n}.csv", np.c_[X, y * 1000], delimiter=",", header="raman_shift_cm1,intensity", comments="", fmt=["%.1f", "%.3f"])
rng = np.random.default_rng(42)
def example(name, y, noise, fluor):
    base = fluor * (1 - (X - 600) / 3000) ** 2 * 800 + 150
    s = y * 1000 + base + rng.normal(0, noise, X.size)
    np.savetxt(OUT / "examples" / f"{name}.csv", np.c_[X, s], delimiter=",", header="raman_shift_cm1,intensity", comments="", fmt=["%.1f", "%.3f"])
example("demo_paracetamol_synthetic", refs["paracetamol"], 8, 1.0)
example("demo_ethanol_synthetic", refs["ethanol"], 10, 1.5)
example("demo_noisy_synthetic", refs["polypropylene"], 400, 1.0)
x2 = np.arange(1000, 1400, 2.0)  # narrow range -> insufficient reference coverage
np.savetxt(OUT / "examples" / "demo_narrow_range_synthetic.csv", np.c_[x2, 200 + 300 / (1 + ((x2 - 1200) / 8) ** 2) + rng.normal(0, 5, x2.size)], delimiter=",", header="raman_shift_cm1,intensity", comments="", fmt=["%.1f", "%.3f"])
LIC = "Generated by data/generate_synthetic.py; no third-party data; free to reuse."
ex = {"demo_paracetamol_synthetic": "Paracetamol-like bands + fluorescence baseline + noise",
      "demo_ethanol_synthetic": "Ethanol-like bands + stronger baseline",
      "demo_noisy_synthetic": "Polypropylene-like bands buried in heavy noise (expected inconclusive)",
      "demo_narrow_range_synthetic": "Only 1000-1400 cm-1 (expected insufficient coverage)"}
json.dump([{"sample_id": k, "description": v, "category": "synthetic", "file": f"{k}.csv", "units": "raman_shift_cm1", "excitation_nm": 532, "source": "synthetic", "license": LIC} for k, v in ex.items()], open(OUT / "examples" / "manifest.json", "w"), indent=2)
json.dump([{"reference_id": n, "name": n.replace("_", " ").title(), "category": "synthetic", "file": f"{n}.csv", "units": "raman_shift_cm1", "excitation_nm": 532, "source": "Lorentzian bands at approximate literature band positions; NOT measured", "license": LIC, "limitations": "Idealised; real spectra differ in relative intensities, widths and instrument response."} for n in BANDS], open(OUT / "references" / "manifest.json", "w"), indent=2)
