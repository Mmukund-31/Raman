    sat = np.minimum(y, np.min(y) + 0.6 * np.ptp(y))
    add("calcite_saturated", "calcite_saturated.csv", "raman_shift_cm1,intensity\n" + fmt_rows(x, sat),
        "Calcite with the detector saturated: the strongest band is clipped flat.", {"expect": "any", "allowed": ["calcite", "inconclusive"],
                                                                                     "warning_contains": "saturated"},
        "derived", RRUFF_LIC, ["saturation warning"])
    gaps = y.copy()
