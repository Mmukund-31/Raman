manifest = []


def lorentz(x, bands):
    return sum(h / (1 + ((x - c) / w) ** 2) for c, h, w in bands)


def rruff_files(material, kind="RAW"):
    """RRUFF files of a material whose specimen is not used as a library reference, best (532 nm) first."""
    out = []
    for f in sorted((RAW / "rruff").glob(f"*/{material.capitalize()}__*Raman_Data_{kind}*.txt")):
        rid = re.match(r"[^_]+__(R\d+)", f.name)
        if rid and ("RRUFF", rid.group(1)) not in IN_LIBRARY:
            out.append(f)
    return sorted(out, key=lambda f: ("__532__" not in f.name, f.name))


def real(material):
    """A held-out PROCESSED specimen of `material` that the app identifies correctly as a plain CSV. Format and
    condition variants are built from it, so a failing variant shows a problem with that variant, not with the
    specimen. (Overall accuracy on unselected specimens is in data/references_real/evaluation.json.)"""
    for f in rruff_files(material, "Processed"):
        s = parse_any(f.read_bytes(), f.name)
        a = pipeline.analyze(s, "pick", "test", None, {}, {"category": "measured"})
        if a["status"] == "ok" and a["matches"][0]["material"] == material:
            return f, s.x, s.y, s.meta
    raise SystemExit(f"No held-out RRUFF specimen of {material} that the app identifies; choose another material.")


def raw_of(processed: pathlib.Path):
    """The RAW export of the same RRUFF measurement, if the archive has it."""
    stem = processed.name.split("__Raman_Data_Processed__")[0]
    return next(iter(sorted(processed.parent.glob(f"{stem}__Raman_Data_RAW__*.txt"))), None)


def add(fid, filename, content, description, expect, source, license_, tests, **extra):
    path = OUT / filename
    path.write_bytes(content if isinstance(content, bytes) else content.encode("utf-8"))
    manifest.append({"id": fid, "file": filename, "description": description, "tests": tests, "expected": expect,
                     "source": source, "license": license_, "size_bytes": path.stat().st_size, **extra})


def fmt_rows(x, y, sep=",", dec=".", xf="{:.2f}", yf="{:.4f}"):
    rows = []
    for a, b in zip(x, y):
        xs, ys = xf.format(a), (yf.format(b) if np.isfinite(b) else "")
        rows.append(f"{xs.replace('.', dec)}{sep}{ys.replace('.', dec)}")
    return "\n".join(rows) + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.iterdir():
        old.unlink()
    m = lambda mat: {"expect": "match", "material": mat}
    inconclusive = {"expect": "inconclusive"}

    # ---- unmodified real exports
    f, x, y, meta = real("calcite")
    fraw = raw_of(f)
    if fraw:
        add("rruff_calcite_raw", "rruff_calcite_raw.txt", fraw.read_bytes(), "Unmodified RRUFF RAW export of a calcite "
            "specimen, with the instrument background. Raw data are harder: calcite or a cautious 'inconclusive' are both "
            "acceptable.", {"expect": "any", "allowed": ["calcite", "inconclusive"]}, f"RRUFF {meta.get('source_id')} ({fraw.name})",
            RRUFF_LIC, ["RRUFF ## header", "raw background", "metadata extraction"])
    add("rruff_calcite_processed", "rruff_calcite_processed.txt", f.read_bytes(), "Unmodified RRUFF processed spectrum of "
        "calcite.", m("calcite"), f"RRUFF {meta.get('source_id')} ({f.name})", RRUFF_LIC, ["RRUFF ## header"])
    f2, *_ = real("quartz")
    add("rruff_quartz_processed", "rruff_quartz_processed.txt", f2.read_bytes(), "Unmodified RRUFF processed spectrum of quartz.",
        m("quartz"), f"RRUFF ({f2.name})", RRUFF_LIC, ["RRUFF ## header"])
    rod = _rod_file()
    if rod:
        add("rod_entry", f"rod_{rod[1]}.rod", rod[0].read_bytes(), f"Unmodified Raman Open Database entry ({rod[2]}) from a "
            "different laboratory than the reference. Band positions can differ between labs by more than the peak "
            "tolerance, so the material or a cautious 'inconclusive' are both acceptable.",
            {"expect": "any", "allowed": [rod[1], "inconclusive"]}, f"ROD {rod[0].stem}", ROD_LIC, ["ROD CIF format", "excitation from file"])

    # ---- the same real calcite spectrum in other layouts
    add("calcite_jcamp", "calcite.jdx", _jcamp(x, y, "Calcite (RRUFF raw)"), "Calcite as JCAMP-DX 5.01 (AFFN X++(Y..Y)).",
        m("calcite"), f"derived from RRUFF {meta.get('source_id')}", RRUFF_LIC, ["JCAMP-DX"])
    fq, xq, yq, mq = real("quartz")
    add("quartz_tsv_units", "quartz_tab_units.tsv", "Raman Shift (cm-1)\tIntensity (a.u.)\n" + fmt_rows(xq, yq, "\t"),
        "Quartz as tab-separated text with units in the header.", m("quartz"), f"derived from {fq.name}", RRUFF_LIC,
        ["tab delimiter", "header with units"])
    fg, xg, yg, mg = real("corundum")
    add("corundum_european_csv", "corundum_european.csv", "Raman-Verschiebung (cm-1);Intensität\n" + fmt_rows(xg, yg, ";", ","),
        "Corundum as a European CSV: semicolon separator, decimal commas, German header.", m("corundum"), f"derived from {fg.name}",
        RRUFF_LIC, ["semicolon delimiter", "decimal comma", "non-English header"])
    fr, xr, yr, mr = real("rutile")
    add("rutile_headerless", "rutile_headerless.txt", "".join(f"  {a:9.3f}   {b:12.3f}\n" for a, b in zip(xr, yr)),
        "Rutile as headerless whitespace-separated columns.", m("rutile"), f"derived from {fr.name}", RRUFF_LIC,
        ["no header", "whitespace delimiter"])
    fd, xd, yd, md = real("dolomite")
    add("dolomite_descending", "dolomite_descending.csv", "raman_shift_cm1,intensity\n" + fmt_rows(xd[::-1], yd[::-1]),
        "Dolomite with the axis stored high-to-low.", m("dolomite"), f"derived from {fd.name}", RRUFF_LIC, ["descending axis"])
    for exc in (532, 785):
        wl = 1e7 / (1e7 / exc - x)
        add(f"calcite_wavelength_{exc}", f"calcite_wavelength_{exc}nm.csv", "wavelength_nm,intensity\n" + fmt_rows(wl, y, xf="{:.4f}"),
            f"Calcite with the x-axis as absolute wavelength (nm) for a {exc} nm laser. Enter {exc} nm as the excitation "
            "wavelength when uploading.", m("calcite"), f"derived from RRUFF {meta.get('source_id')}", RRUFF_LIC,
            ["wavelength axis", "needs excitation"], excitation_nm=exc)
    add("calcite_wavelength_no_excitation", "calcite_wavelength_missing_laser.csv", "wavelength_nm,intensity\n"
        + fmt_rows(1e7 / (1e7 / 532 - x), y, xf="{:.4f}"), "Wavelength axis uploaded without an excitation wavelength.",
        {"expect": "error", "message_contains": "excitation"}, "derived", RRUFF_LIC, ["error message: missing excitation"])
    fh, xh, yh, mh = real("hematite")
    pre = ("Instrument: Generic dispersive Raman\nOperator: test\nDate: 2026-10-23 14:02\nLaser Wavelength: "
           f"{mh.get('excitation_nm', 532):g} nm\nLaser Power: 250 mW\nExposure (s): 10\nAccumulations: 3\n\n")
    add("hematite_instrument_preamble", "hematite_instrument_export.txt", pre + "Shift [1/cm],Counts\n" + fmt_rows(xh, yh)
        + "\n--- end of data ---\n", "Hematite with an instrument metadata preamble and a footer line.", m("hematite"),
        f"derived from {fh.name}", RRUFF_LIC, ["metadata preamble", "footer", "excitation read from file", "laser power not mistaken for wavelength"])
    add("calcite_absolute_wavenumber", "calcite_absolute_wavenumber.csv", "# excitation 532 nm\nAbsolute wavenumber (cm-1),Intensity\n"
        + fmt_rows(1e7 / 532 - x, y), "Calcite stored as absolute wavenumbers (cm⁻¹); the 532 nm laser is noted in the file.",
        m("calcite"), "derived", RRUFF_LIC, ["absolute wavenumber axis"])

    # ---- several spectra in one file
